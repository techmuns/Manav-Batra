export function devMockYearsFor(ticker: string): Y[] | undefined {
  const byYear = DEV_MOCK_FINANCIALS[ticker];
  if (!byYear) return undefined;
  return Object.values(byYear).sort((a, b) =>
    a.fiscalYear.localeCompare(b.fiscalYear)
  );
}

